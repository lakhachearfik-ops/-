let mode = "morning";
let current = [];

const list = document.getElementById("adhkarList");
const title = document.getElementById("pageTitle");
const progressText = document.getElementById("progressText");
const progressBar = document.getElementById("progressBar");
const doneBox = document.getElementById("doneBox");

const modeNames = {
morning: "أذكار الصباح",
evening: "أذكار المساء",
sleep: "أذكار النوم",
wake: "أذكار الاستيقاظ",
prayer: "أذكار بعد الصلاة",
home: "أذكار المنزل",
travel: "أذكار السفر"
};

function loadMode(newMode) {
mode = newMode;

current = adhkar[mode].map(x => ({
...x,
done: 0
}));

title.textContent = modeNames[mode] || "الأذكار";

document.querySelectorAll(".tab").forEach(btn => {
btn.classList.toggle("active", btn.dataset.mode === mode);
});

render();
}

function render() {
list.innerHTML = "";

current.forEach((item, i) => {
const card = document.createElement("article");

card.className =
  "card" +
  (item.done >= item.count ? " completed" : "");

const left = item.count - item.done;

card.innerHTML = `
  <div class="card-top">
    <span class="number">${i + 1}</span>
    <span class="count-label">
      المطلوب: ${item.count} مرة
    </span>
  </div>

  <div class="zekr">
    ${item.text.replace(/\n/g, "<br>")}
  </div>

  <div class="reference">
    ${item.ref}
  </div>

  <button
    class="counter ${left === 0 ? "done-btn" : ""}"
    data-i="${i}">
    ${
      left === 0
        ? "✓ اكتمل الذكر"
        : `اضغط للعدّ — ${item.done} / ${item.count}`
    }
  </button>
`;

list.appendChild(card);

});

updateProgress();
}

function updateProgress() {
const completed = current.filter(
x => x.done >= x.count
).length;

progressText.textContent =
"${completed} / ${current.length}";

progressBar.style.width =
"${(completed / current.length) * 100}%";

doneBox.style.display =
completed === current.length
? "block"
: "none";
}

list.addEventListener("click", e => {
const btn = e.target.closest(".counter");

if (!btn) return;

const i = Number(btn.dataset.i);

if (current[i].done < current[i].count) {
current[i].done++;
}

render();
});

document.querySelectorAll(".tab").forEach(btn => {
btn.addEventListener("click", () => {
loadMode(btn.dataset.mode);
});
});

document.getElementById("resetAll").addEventListener("click", () => {
current.forEach(x => {
x.done = 0;
});

render();

window.scrollTo({
top: 0,
behavior: "smooth"
});
});

loadMode("morning");
